'use client';

import { useCallback, useEffect, useState } from 'react';

type Role = 'collaborateur' | 'admin' | 'operateur';
type Member = { id: string; email: string; name: string; role: Role; canValidate: boolean; brandId: string | null; isActive: boolean };

const ROLE_LABELS: Record<Role, string> = { collaborateur: 'Collaborateur', admin: 'Administrateur', operateur: 'Opérateur KÔMIAN' };
const ROLE_HELP: Array<[Role, string]> = [
  ['collaborateur', 'crée et modifie ses vidéos, les envoie en validation, voit le solde et ses dépenses. Avec « Peut valider », il approuve aussi les vidéos de l’équipe.'],
  ['admin', 'en plus : gère l’équipe et la médiathèque, valide toujours, suit les crédits et leur historique.'],
  ['operateur', 'équipe KÔMIAN : tarifs, crédits, coûts de production et paramètres internes.'],
];

const field = 'min-h-11 w-full rounded-md border border-[#d4d4d8] bg-white px-3 text-sm font-normal outline-none focus:border-[#c51e1c] focus-visible:ring-2 focus-visible:ring-[#c51e1c]/20';

/**
 * Équipe (27/10): roles in plain words, the right to validate as a switch, no departments. A temporary password is
 * generated by the server, shown once, and must be changed by the person at first sign-in.
 */
export function TeamManager() {
  const [members, setMembers] = useState<Member[]>([]);
  const [roles, setRoles] = useState<Role[]>(['collaborateur', 'admin']);
  const [currentUserId, setCurrentUserId] = useState('');
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [busy, setBusy] = useState('');
  const [temporary, setTemporary] = useState<{ name: string; password: string } | null>(null);
  const [copied, setCopied] = useState(false);
  const [form, setForm] = useState<{ name: string; email: string; role: Role; canValidate: boolean }>({ name: '', email: '', role: 'collaborateur', canValidate: false });

  const load = useCallback(async () => {
    const response = await fetch('/api/admin/users', { cache: 'no-store' });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.error ?? 'Impossible de charger l’équipe.');
    setMembers(data.users ?? []);
    if (Array.isArray(data.assignableRoles)) setRoles(data.assignableRoles);
    setCurrentUserId(data.currentUserId ?? '');
  }, []);
  useEffect(() => { void load().catch((cause) => setError(cause instanceof Error ? cause.message : 'Impossible de charger l’équipe.')); }, [load]);

  async function send(method: 'POST' | 'PATCH' | 'DELETE', body: Record<string, unknown>) {
    const response = await fetch('/api/admin/users', { method, headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.error ?? 'La modification n’a pas pu être enregistrée.');
    return data;
  }
  async function run(key: string, action: () => Promise<void>) {
    setBusy(key); setError(''); setNotice('');
    try { await action(); await load(); } catch (cause) { setError(cause instanceof Error ? cause.message : 'Une erreur est survenue.'); } finally { setBusy(''); }
  }
  function showPassword(name: string, password: string | undefined) {
    if (password) { setTemporary({ name, password }); setCopied(false); }
  }

  const create = (event: React.FormEvent) => {
    event.preventDefault();
    void run('create', async () => {
      const data = await send('POST', { name: form.name, email: form.email, role: form.role, canValidate: form.role === 'collaborateur' && form.canValidate });
      showPassword(form.name, data.temporaryPassword);
      setNotice(`Compte créé pour ${form.name}.`);
      setForm({ name: '', email: '', role: 'collaborateur', canValidate: false });
    });
  };
  const update = (member: Member, patch: Partial<Pick<Member, 'role' | 'canValidate' | 'isActive'>>) => void run(member.id, async () => { await send('PATCH', { id: member.id, ...patch }); });
  const resetPassword = (member: Member) => {
    if (!window.confirm(`Réinitialiser le mot de passe de ${member.name || member.email} ? Son mot de passe actuel ne fonctionnera plus ; un mot de passe provisoire vous sera affiché une seule fois.`)) return;
    void run(member.id, async () => { const data = await send('PATCH', { id: member.id, resetPassword: true }); showPassword(member.name || member.email, data.temporaryPassword); });
  };
  const remove = (member: Member) => {
    if (!window.confirm(`Supprimer définitivement ${member.name || member.email} ? Il ne pourra plus se connecter et disparaîtra de l’équipe. Ses vidéos et ses dépenses restent dans l’historique. Cette action est irréversible.`)) return;
    void run(member.id, async () => {
      const data = await send('DELETE', { id: member.id });
      setNotice(data.mode === 'archived' ? `${member.name || member.email} est retiré de l’équipe. Ses vidéos et ses dépenses restent dans l’historique.` : `${member.name || member.email} est supprimé.`);
    });
  };
  async function copy() {
    if (!temporary) return;
    try { await navigator.clipboard.writeText(temporary.password); setCopied(true); } catch { setCopied(false); }
  }

  return <div className="space-y-6">
    {error && <p role="alert" className="border border-[#f0c9c6] bg-[#fae9e7] p-4 text-sm text-[#9d352e]">{error}</p>}
    {notice && <p role="status" className="border border-[#d7e7da] bg-[#f2f8f3] p-4 text-sm text-[#315c39]">{notice}</p>}
    {temporary && <section aria-labelledby="temporary-password-title" className="border border-[#eadfc7] bg-[#fbf6ed] p-4">
      <h2 id="temporary-password-title" className="text-sm font-semibold text-[#54462d]">Mot de passe provisoire de {temporary.name}</h2>
      <p className="mt-1 text-xs leading-5 text-[#675432]">Transmettez-le de vive voix ou par message : il ne sera plus affiché. La personne devra le changer à sa première connexion.</p>
      <div className="mt-3 flex flex-wrap items-center gap-2">
        <code className="select-all rounded-sm bg-white px-3 py-2 font-mono text-sm text-[#161619]">{temporary.password}</code>
        <button type="button" onClick={() => void copy()} className="min-h-11 rounded-sm border border-[#d4d4d8] bg-white px-4 text-xs font-semibold hover:bg-[#f7f7f8]">{copied ? 'Copié' : 'Copier'}</button>
        <button type="button" onClick={() => setTemporary(null)} className="min-h-11 rounded-sm bg-[#161619] px-4 text-xs font-semibold text-white">J’ai transmis le mot de passe</button>
      </div>
    </section>}

    <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_340px]">
      <section aria-labelledby="team-title" className="border border-[var(--border)] bg-white">
        <div className="border-b border-[var(--border)] px-5 py-4">
          <h2 id="team-title" className="text-sm font-semibold">Membres</h2>
          <ul className="mt-2 space-y-1 text-xs leading-5 text-[#626269]">{ROLE_HELP.filter(([role]) => roles.includes(role)).map(([role, help]) => <li key={role}><b className="font-semibold text-[#161619]">{ROLE_LABELS[role]}</b> : {help}</li>)}</ul>
        </div>
        {members.length === 0 ? <p className="px-6 py-10 text-center text-xs text-[#626269]">Aucun membre pour l’instant.</p> : <ul className="divide-y divide-[var(--border)]">
          {members.map((member) => {
            const self = member.id === currentUserId;
            const alwaysValidates = member.role !== 'collaborateur';
            const label = member.name || member.email;
            return <li key={member.id} className="grid gap-3 px-5 py-4 md:grid-cols-[minmax(0,1fr)_minmax(210px,240px)] md:items-start 2xl:grid-cols-[minmax(0,1fr)_minmax(210px,240px)_auto] 2xl:items-center">
              <div className="min-w-0"><p className="truncate text-sm font-semibold">{label}{self && <span className="ml-2 text-xs font-normal text-[#626269]">(vous)</span>}</p><p className="truncate text-xs text-[#626269]">{member.email}</p>{!member.isActive && <p className="mt-1 text-xs font-semibold text-[#77591f]">Accès désactivé</p>}</div>
              <div className="grid gap-2">
                <label className="grid gap-1 text-xs font-semibold text-[#4b4b50]">Rôle
                  <select aria-label={`Rôle de ${label}`} value={member.role} disabled={busy === member.id || self || !roles.includes(member.role)} onChange={(event) => update(member, { role: event.target.value as Role })} className={field}>
                    {(roles.includes(member.role) ? roles : [member.role]).map((role) => <option key={role} value={role}>{ROLE_LABELS[role]}</option>)}
                  </select>
                </label>
                <label className={`flex min-h-11 items-center gap-2 text-xs ${alwaysValidates ? 'text-[#626269]' : 'text-[#161619]'}`}>
                  <input type="checkbox" className="size-4 accent-[#c51e1c]" checked={alwaysValidates || member.canValidate} disabled={alwaysValidates || busy === member.id} onChange={(event) => update(member, { canValidate: event.target.checked })} />
                  {alwaysValidates ? 'Valide toujours (administration)' : 'Peut valider les vidéos'}
                </label>
              </div>
              <div className="flex flex-wrap gap-2 md:col-span-2 2xl:col-span-1 2xl:justify-end">
                {!self && <button type="button" disabled={busy === member.id} onClick={() => update(member, { isActive: !member.isActive })} className="min-h-11 rounded-sm border border-[#d4d4d8] px-3 text-xs font-semibold hover:bg-[#f7f7f8] disabled:opacity-50">{member.isActive ? 'Désactiver' : 'Réactiver'}</button>}
                <button type="button" disabled={busy === member.id} onClick={() => resetPassword(member)} className="min-h-11 rounded-sm border border-[#d4d4d8] px-3 text-xs font-semibold hover:bg-[#f7f7f8] disabled:opacity-50">Réinitialiser le mot de passe</button>
                {!self && <button type="button" disabled={busy === member.id} onClick={() => remove(member)} aria-label={`Supprimer ${label}`} className="min-h-11 rounded-sm px-3 text-xs font-semibold text-[#9d352e] underline underline-offset-4 hover:text-[#7c241f] disabled:opacity-50">Supprimer</button>}
              </div>
            </li>;
          })}
        </ul>}
      </section>

      <form onSubmit={create} aria-labelledby="add-member-title" className="h-fit space-y-4 border border-[var(--border)] bg-white p-5">
        <div><h2 id="add-member-title" className="text-sm font-semibold">Ajouter un membre</h2><p className="mt-1 text-xs leading-5 text-[#626269]">Un mot de passe provisoire est créé et vous est affiché une seule fois. Aucun e-mail n’est envoyé.</p></div>
        <label className="grid gap-1.5 text-xs font-semibold">Nom complet<input value={form.name} onChange={(event) => setForm({ ...form, name: event.target.value })} required minLength={2} maxLength={120} autoComplete="off" className={field} /></label>
        <label className="grid gap-1.5 text-xs font-semibold">Adresse e-mail<input type="email" value={form.email} onChange={(event) => setForm({ ...form, email: event.target.value })} required autoComplete="off" className={field} /></label>
        <label className="grid gap-1.5 text-xs font-semibold">Rôle<select value={form.role} onChange={(event) => setForm({ ...form, role: event.target.value as Role })} className={field}>{roles.map((role) => <option key={role} value={role}>{ROLE_LABELS[role]}</option>)}</select></label>
        {form.role === 'collaborateur' && <label className="flex min-h-11 items-center gap-2 text-xs"><input type="checkbox" className="size-4 accent-[#c51e1c]" checked={form.canValidate} onChange={(event) => setForm({ ...form, canValidate: event.target.checked })} />Peut valider les vidéos de l’équipe</label>}
        <button disabled={busy === 'create'} className="min-h-11 w-full rounded-sm bg-[#c51e1c] px-4 text-xs font-semibold text-white hover:bg-[#a71715] disabled:opacity-50">{busy === 'create' ? 'Création…' : 'Créer le compte'}</button>
      </form>
    </div>
  </div>;
}
